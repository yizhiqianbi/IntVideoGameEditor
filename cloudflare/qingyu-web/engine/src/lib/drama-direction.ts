export function singleShotDirection(duration?: number) {
  const n = parseShotDuration(duration);
  return `规格：${n}秒 | 24fps | 写实连续单镜头。同一空间、连续时间、一条运镜；禁止内部切镜、跳切、蒙太奇和黑场。动作要有重量、惯性和接触点。`;
}

