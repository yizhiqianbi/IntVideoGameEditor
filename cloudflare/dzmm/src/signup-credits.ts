import type { Env } from "./types";

/** A server-owned, one-time registration gift. It is neither a purchase nor a
 * VIP daily check-in. Login never backfills it. */
export const NEW_SIGNUP_CREDITS = 300;

/** A new device (guest session) gets enough to try the tavern once before the
 * account gate. Registered accounts get the larger signup gift instead. */
export const NEW_GUEST_CREDITS = 100;

/** One welcome grant per browser session; the grant key makes retries idempotent. */
export function guestWelcomeCreditStatement(env: Pick<Env, "DB">, userId: string, createdAt: number) {
  return env.DB.prepare(`INSERT INTO trusted_credit_grants(grant_key,user_id,credits,reason,created_at)
    VALUES('guest_welcome:' || ?1,?1,?2,'guest_welcome',?3)
    ON CONFLICT(grant_key) DO NOTHING`)
    .bind(userId, NEW_GUEST_CREDITS, createdAt);
}

export function publicSignupCreditConfig() {
  return {
    enabled: true,
    credits: NEW_SIGNUP_CREDITS,
    targetConversationRounds: 10,
    includesAutomaticReplySuggestions: true,
    oncePerAccount: true,
    billingRule: "actual_cost_x3" as const,
    note: "新注册一次赠送 300 Credit。实际可用轮数受模型、上下文和回复长度影响；预留并非实际扣费，未使用部分返还，按实际成本的三倍计费。",
  };
}

/** Join the registration batch after its account/session writes. The nonce is
 * generated by the server and can only match the transaction that converted
 * this account into a registered user. Never run this as a login backfill. */
export function passwordSignupCreditStatement(
  env: Pick<Env, "DB">,
  userId: string,
  registrationNonce: string,
  createdAt: number,
) {
  return env.DB.prepare(`INSERT INTO trusted_credit_grants(grant_key,user_id,credits,reason,created_at)
    SELECT 'new_signup:' || u.id,u.id,?,'new_signup',? FROM users u
    WHERE u.id=? AND u.is_guest=0 AND u.mutation_token=?
    ON CONFLICT(grant_key) DO NOTHING`)
    .bind(NEW_SIGNUP_CREDITS, createdAt, userId, registrationNonce);
}

/** Only a successfully claimed challenge with registered=1 may award a gift.
 * An existing email owner has registered=0, even if verification rotates its
 * sessions or password. Appending this to the claim batch makes failure atomic. */
export function emailSignupCreditStatement(
  env: Pick<Env, "DB">,
  challengeId: string,
  registrationNonce: string,
  createdAt: number,
) {
  return env.DB.prepare(`INSERT INTO trusted_credit_grants(grant_key,user_id,credits,reason,created_at)
    SELECT 'new_signup:' || u.id,u.id,?,'new_signup',? FROM email_auth_challenges c JOIN users u ON u.id=c.target_user_id
    WHERE c.id=? AND c.claim_nonce=? AND c.registered=1 AND u.mutation_token=? AND u.is_guest=0
    ON CONFLICT(grant_key) DO NOTHING`)
    .bind(NEW_SIGNUP_CREDITS, createdAt, challengeId, registrationNonce, registrationNonce);
}
