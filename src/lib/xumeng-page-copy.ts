const CREDIT_LABEL: Partial<Record<XumengLocale, string>> = { "zh-Hans": "金币", "zh-Hant": "金幣" };
function withCreditLabel<T extends object>(copy: T, locale: XumengLocale): T {
  const label = CREDIT_LABEL[locale];
  if (!label) return copy;
  return Object.fromEntries(Object.entries(copy).map(([key, value]) => [key, typeof value === "string" ? value.replace(/\bCredit\b/g, label) : value])) as T;
}

export function xumengPage(locale: XumengLocale): XumengPageCopy {
  return withCreditLabel(PAGE[locale] ?? PAGE[XUMENG_DEFAULT_LOCALE], locale);
}

export function xumengPageFill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(values[name] ?? ""));
}

